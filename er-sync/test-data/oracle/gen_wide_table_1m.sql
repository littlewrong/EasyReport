-- 向 TEST_WIDE_TABLE 批量插入 100 万条测试数据（Oracle）
-- 使用方法：先执行 oracle_test_data.sql，再执行本脚本
-- ============================================================

INSERT INTO "TEST_WIDE_TABLE"
    ("ID", "COMPANY", "DEPARTMENT", "EMPLOYEE", "TITLE", "SALARY", "BONUS", "TAX_RATE",
     "HIRE_DATE", "CONTRACT_END", "WORK_YEARS", "LEVEL", "IS_MANAGER",
     "KPI_SCORE", "OFFICE_ADDR", "MEMO", "CREATE_TIME", "UPDATE_TIME", "TIME_STAMP")
SELECT
    LOWER(REGEXP_REPLACE(RAWTOHEX(SYS_GUID()), '(.{8})(.{4})(.{4})(.{4})(.{12})', '\1-\2-\3-\4-\5')),
    '公司' || ELT_COMPANY,
    ELT_DEPT,
    '员工' || LPAD(CEIL(RN / 10), 6, '0'),
    ELT_TITLE,
    ROUND(8000 + DBMS_RANDOM.VALUE(0, 42000), 2),
    ROUND(DBMS_RANDOM.VALUE(0, 20000), 2),
    ROUND(0.03 + DBMS_RANDOM.VALUE(0, 0.32), 4),
    TRUNC(SYSDATE) - FLOOR(DBMS_RANDOM.VALUE(0, 5475)),
    TRUNC(SYSDATE) + FLOOR(DBMS_RANDOM.VALUE(0, 1825)),
    FLOOR(DBMS_RANDOM.VALUE(0, 15)),
    GREATEST(1, LEAST(10, FLOOR(DBMS_RANDOM.VALUE(0, 10)) + 1)),
    CASE WHEN DBMS_RANDOM.VALUE(0, 1) < 0.2 THEN 1 ELSE 0 END,
    ROUND(60 + DBMS_RANDOM.VALUE(0, 40), 1),
    ELT_CITY || ELT_SITE || TO_CHAR(FLOOR(DBMS_RANDOM.VALUE(1, 21))) || '层',
    CASE WHEN DBMS_RANDOM.VALUE(0, 1) < 0.3 THEN '备注-' || TO_CHAR(RN) || ': ' || ELT_MEMO ELSE NULL END,
    LOCALTIMESTAMP - NUMTODSINTERVAL(FLOOR(DBMS_RANDOM.VALUE(0, 1095)), 'DAY'),
    LOCALTIMESTAMP - NUMTODSINTERVAL(FLOOR(DBMS_RANDOM.VALUE(0, 1095)), 'DAY'),
    LOCALTIMESTAMP - NUMTODSINTERVAL(FLOOR(DBMS_RANDOM.VALUE(0, 1095)), 'DAY')
FROM (
    SELECT LEVEL AS RN,
           CASE MOD(LEVEL - 1, 10) WHEN 0 THEN 'Alpha科技' WHEN 1 THEN 'Beta制造' WHEN 2 THEN 'Gamma贸易' WHEN 3 THEN 'Delta金融' WHEN 4 THEN 'Epsilon互联' WHEN 5 THEN 'Zeta医疗' WHEN 6 THEN 'Eta教育' WHEN 7 THEN 'Theta物流' WHEN 8 THEN 'Iota能源' ELSE 'Kappa零售' END AS ELT_COMPANY,
           CASE FLOOR(DBMS_RANDOM.VALUE(0, 8)) WHEN 0 THEN '研发部' WHEN 1 THEN '产品部' WHEN 2 THEN '市场部' WHEN 3 THEN '销售部' WHEN 4 THEN '财务部' WHEN 5 THEN '人事部' WHEN 6 THEN '运营部' ELSE '法务部' END AS ELT_DEPT,
           CASE FLOOR(DBMS_RANDOM.VALUE(0, 10)) WHEN 0 THEN '初级工程师' WHEN 1 THEN '中级工程师' WHEN 2 THEN '高级工程师' WHEN 3 THEN '架构师' WHEN 4 THEN '产品经理' WHEN 5 THEN '技术总监' WHEN 6 THEN '项目经理' WHEN 7 THEN '数据分析师' WHEN 8 THEN 'HR专员' ELSE '财务主管' END AS ELT_TITLE,
           CASE FLOOR(DBMS_RANDOM.VALUE(0, 8)) WHEN 0 THEN '北京' WHEN 1 THEN '上海' WHEN 2 THEN '广州' WHEN 3 THEN '深圳' WHEN 4 THEN '杭州' WHEN 5 THEN '成都' WHEN 6 THEN '武汉' ELSE '西安' END AS ELT_CITY,
           CASE FLOOR(DBMS_RANDOM.VALUE(0, 3)) WHEN 0 THEN '总部' WHEN 1 THEN '分部' ELSE 'CBD' END AS ELT_SITE,
           CASE FLOOR(DBMS_RANDOM.VALUE(0, 4)) WHEN 0 THEN '核心骨干' WHEN 1 THEN '待晋升' WHEN 2 THEN '绩效观察期' ELSE '外派人员' END AS ELT_MEMO
    FROM dual CONNECT BY LEVEL <= 1000000
);

COMMIT;
SELECT COUNT(*) AS total_rows FROM "TEST_WIDE_TABLE";
